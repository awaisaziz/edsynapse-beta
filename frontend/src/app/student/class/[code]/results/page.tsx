"use client";

import { use, useState, useEffect, useMemo } from "react";
import { useSearchParams } from "next/navigation";
import Link from "next/link";
import { AppShell } from "@/components/ui/AppShell";
import { ProgressRing } from "@/components/ui/ProgressRing";
import { KnowledgeMapChart } from "@/components/ui/KnowledgeMapChart";
import { QuizCard } from "@/components/ui/QuizCard";
import Markdown from "@/components/ui/Markdown";
import { type KnowledgeMapTopic, type TopicMastery } from "@/lib/knowledgeMap";
import { readReport, type CachedReport } from "@/lib/assessmentStore";
import {
  Trophy,
  ArrowRight,
  Download,
  Printer,
  ArrowLeft,
  Sparkles,
} from "lucide-react";

const LEVEL_SCORE: Record<TopicMastery, number> = {
  strong: 88,
  moderate: 60,
  needs_improvement: 32,
};

export default function ResultsPage({ params }: { params: Promise<{ code: string }> }) {
  const { code } = use(params);
  const searchParams = useSearchParams();
  const reportId = searchParams.get("report");

  const [cached, setCached] = useState<CachedReport | null>(null);
  const [isDownloading, setIsDownloading] = useState(false);

  useEffect(() => {
    if (reportId) setCached(readReport(reportId));
  }, [reportId]);

  const report = cached?.report ?? null;

  const score = useMemo(() => {
    if (!report) return { correct: 0, total: 0, percentage: 0 };
    return {
      correct: report.correct,
      total: report.total,
      percentage: report.total > 0 ? Math.round((report.correct / report.total) * 100) : 0,
    };
  }, [report]);

  const mapTopics: KnowledgeMapTopic[] = useMemo(() => {
    if (!report) return [];
    return report.knowledge_map.topics.map((t, i) => ({
      id: `km_${i}`,
      topic: t.topic,
      status: t.level,
      score: LEVEL_SCORE[t.level],
      lastAttempted: "Just now",
      quizAttempts: 0,
    }));
  }, [report]);

  const recommendation = report?.per_question.find((r) => !r.correct)
    ? report.topic
    : report?.updated_status.topic ?? "";

  const handleDownloadPDF = () => {
    if (!report) return;
    setIsDownloading(true);
    setTimeout(() => {
      setIsDownloading(false);
      const reportText = `
=========================================
          EDSYNAPSE GRADE REPORT
=========================================
Course Code: ${code}
Topic: ${report.topic}
Score: ${score.percentage}% (${score.correct}/${score.total} Correct)
Mastery Level: ${report.updated_status.level.replace(/_/g, " ")}

QUESTION BREAKDOWN:
${report.per_question
  .map(
    (r, idx) =>
      `${idx + 1}. [${r.correct ? "CORRECT" : "INCORRECT"}]
   Your Answer: ${r.student_response || "—"}
   Correct Answer: ${r.correct_answer}
   Explanation: ${r.rationale}
`,
  )
  .join("\n")}

Generated by EdSynapse AI Tutor.
=========================================
      `;
      const blob = new Blob([reportText], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `edsynapse_${code}_grade_report.txt`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    }, 800);
  };

  const handlePrint = () => window.print();

  if (!report) {
    return (
      <AppShell role="student">
        <div className="max-w-2xl mx-auto py-24 text-center space-y-3">
          <h1 className="text-xl font-bold text-foreground font-display">Report unavailable</h1>
          <p className="text-sm text-muted-foreground">
            This grade report has expired or wasn&apos;t found. Take an assessment to generate a fresh report.
          </p>
          <Link
            href={`/student/class/${code}/assessment`}
            className="inline-flex items-center gap-2 px-5 py-3 bg-primary text-white rounded-2xl text-sm font-bold hover:bg-primary/95 transition-all"
          >
            <ArrowLeft className="w-4 h-4" />
            <span>Go to Assessments</span>
          </Link>
        </div>
      </AppShell>
    );
  }

  return (
    <AppShell role="student">
      <div className="max-w-4xl mx-auto space-y-8 print:p-0 print:max-w-full">
        {/* Celebration Header */}
        <div className="text-center space-y-4 print:hidden edsynapse-stagger">
          <div className="inline-flex p-4 rounded-3xl bg-amber-500/10 text-amber-500 border border-amber-500/20">
            <Trophy className="w-12 h-12" />
          </div>
          <div className="space-y-2">
            <h1 className="text-3xl font-black text-foreground font-display tracking-tight">Assessment Completed!</h1>
            <p className="text-sm text-muted-foreground max-w-md mx-auto">
              The AI Tutor has graded your responses on <span className="font-bold">{report.topic}</span> and updated your
              knowledge map.
            </p>
          </div>
        </div>

        {/* Score Card / Overview */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-6 items-stretch">
          <div className="liquid-panel rounded-3xl p-6 flex flex-col items-center justify-center text-center gap-4">
            <span className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
              Final Assessment Score
            </span>
            <ProgressRing value={score.percentage} size={130} strokeWidth={10} textClassName="text-2xl font-black text-primary" />
            <p className="text-xs font-semibold text-muted-foreground">
              {score.correct} of {score.total} questions correct
            </p>
          </div>

          {/* Mastery feedback card */}
          <div className="liquid-panel rounded-3xl p-6 flex flex-col justify-between gap-6 relative overflow-hidden">
            <div className="space-y-3">
              <span className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">Updated Mastery</span>
              <h3 className="text-lg font-bold text-foreground font-display capitalize">
                {report.updated_status.level.replace(/_/g, " ")}
              </h3>
              <Markdown className="text-xs text-muted-foreground leading-relaxed">{report.updated_status.evidence}</Markdown>
            </div>

            {recommendation && (
              <div className="flex items-center gap-2 text-primary bg-primary/5 border border-primary/10 px-3.5 py-2 rounded-2xl w-fit">
                <Sparkles className="w-4 h-4" />
                <span className="text-xs font-bold">Focus next: {recommendation}</span>
              </div>
            )}
          </div>

          {/* Action buttons card */}
          <div className="liquid-panel rounded-3xl p-6 flex flex-col justify-between gap-6 print:hidden">
            <div className="space-y-1.5">
              <span className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">Action Center</span>
              <h3 className="text-sm font-bold text-foreground font-display">Save or Print Report</h3>
              <p className="text-xs text-muted-foreground">Export your summary and question breakdowns.</p>
            </div>

            <div className="space-y-2">
              <button
                type="button"
                onClick={handleDownloadPDF}
                disabled={isDownloading}
                className="w-full flex items-center justify-center gap-2 py-3 bg-primary text-white rounded-2xl text-xs font-bold hover:bg-primary/95 transition-all shadow-lg shadow-primary/20 active:scale-[0.98] disabled:opacity-50"
              >
                {isDownloading ? (
                  <div className="w-4 h-4 animate-spin rounded-full border-2 border-white/30 border-t-white" />
                ) : (
                  <Download className="w-4 h-4" />
                )}
                <span>{isDownloading ? "Generating Report..." : "Download Report"}</span>
              </button>

              <button
                type="button"
                onClick={handlePrint}
                className="w-full flex items-center justify-center gap-2 py-3 bg-white/60 hover:bg-white text-foreground rounded-2xl text-xs font-bold border border-primary/10 transition-all active:scale-[0.98]"
              >
                <Printer className="w-4 h-4" />
                <span>Print Grade Slip</span>
              </button>
            </div>
          </div>
        </div>

        {/* Detailed Question Review */}
        <div className="space-y-6">
          <div className="flex items-center justify-between border-b border-white/30 pb-2">
            <h2 className="text-sm font-bold text-foreground uppercase tracking-wider font-display">
              Question-by-Question Breakdown
            </h2>
            <span className="text-xs text-muted-foreground font-semibold">
              {report.per_question.length} questions reviewed
            </span>
          </div>

          <div className="space-y-4">
            {report.per_question.map((r, idx) => {
              const q = cached?.questions.find((x) => x.id === r.question_id);
              const isMcq = q?.type === "mcq" && !!q.choices?.length;

              if (isMcq && q?.choices) {
                // Show the full option list and highlight the picked vs. correct
                // choice. The grade report stores the student's MCQ response as
                // the option text, and the correct option via the question's
                // correct_label — map both back to option indices for QuizCard.
                const options = q.choices.map((c) => `${c.label}. ${c.text}`);
                const selectedIndex = q.choices.findIndex((c) => c.text === r.student_response);
                const correctIndex = q.choices.findIndex((c) => c.label === q.correct_label);
                return (
                  <QuizCard
                    key={r.question_id}
                    index={idx}
                    question={q.prompt}
                    type="mcq"
                    options={options}
                    selectedAnswer={selectedIndex >= 0 ? String(selectedIndex) : ""}
                    onSelectAnswer={() => {}}
                    correctAnswer={correctIndex >= 0 ? String(correctIndex) : ""}
                    showResults={true}
                    explanation={r.rationale}
                  />
                );
              }

              return (
                <QuizCard
                  key={r.question_id}
                  index={idx}
                  question={q?.prompt ?? `Question ${idx + 1}`}
                  type={(q?.type ?? "short_answer") as "mcq" | "short_answer"}
                  selectedAnswer={r.student_response}
                  onSelectAnswer={() => {}}
                  correctAnswer={r.correct_answer}
                  showResults={true}
                  explanation={r.rationale}
                />
              );
            })}
          </div>
        </div>

        {/* Updated Knowledge Map Preview */}
        {mapTopics.length > 0 && (
          <div className="space-y-6">
            <div className="flex items-center justify-between border-b border-white/30 pb-2">
              <h2 className="text-sm font-bold text-foreground uppercase tracking-wider font-display">
                Updated Topic Mastery
              </h2>
              <span className="text-xs text-muted-foreground font-semibold">Live feedback sync</span>
            </div>

            <KnowledgeMapChart topics={mapTopics} className="pointer-events-none opacity-90" />
          </div>
        )}

        {/* Footer Navigation */}
        <div className="flex items-center justify-between pt-4 print:hidden">
          <Link
            href={`/student/class/${code}/assessment`}
            className="flex items-center gap-2 px-4 py-3 rounded-2xl text-sm font-semibold text-muted-foreground hover:bg-white/40 transition-all border border-transparent hover:border-white/50"
          >
            <ArrowLeft className="w-4 h-4" strokeWidth={2} />
            <span>All Attempts</span>
          </Link>

          <Link
            href="/student/knowledge-map"
            className="flex items-center gap-2 px-5 py-3 bg-gradient-to-r from-emerald-600 to-teal-600 text-white rounded-2xl text-sm font-semibold hover:brightness-110 shadow-lg shadow-emerald-500/20 active:scale-[0.98] transition-all"
          >
            <span>View Full Knowledge Map</span>
            <ArrowRight className="w-4 h-4" />
          </Link>
        </div>
      </div>
    </AppShell>
  );
}
